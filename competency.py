_COMPILED = [(c, re.compile(c['pattern'], re.IGNORECASE)) for c in COMPETENCIES]


_PUNCT = set('.,;:!?()[]"\'')


def _whole_word(text, m):
    """Expand a regex hit to the full word around it, e.g. 'חלופ' -> 'חלופות'."""
    a, b = m.start(), m.end()
    while a > 0 and not text[a - 1].isspace() and text[a - 1] not in _PUNCT: a -= 1
    while b < len(text) and not text[b].isspace() and text[b] not in _PUNCT: b += 1
    return text[a:b]


def preliminary_evidence(messages, lang='he'):
    user_texts = [m.content for m in messages if m.role == 'user']
    combined = ' '.join(user_texts)
    signals = []
    for comp, rx in _COMPILED:
        hits = sorted({_whole_word(combined, m).lower() for m in rx.finditer(combined)})
        signals.append({'key': comp['key'], 'name': t(comp, lang)['name'],
                        'found': bool(hits), 'hits': hits[:6]})
    note = ('مؤشرات أولية بالكلمات المفتاحية فقط. لا يُحدد مستوى تلقائيًا: يجب فحص الجودة والاستقلالية والأدلة عبر الزمن.'
            if lang == 'ar' else
            'סימנים ראשוניים לפי מילות מפתח בלבד. לא נקבעת רמה אוטומטית: יש לבחון איכות, עצמאות וראיות לאורך זמן.')
    return {'turns': len(user_texts), 'signals': signals, 'note': note}


